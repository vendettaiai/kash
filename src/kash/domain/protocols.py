class NotificationRepository(Protocol):
    """Protocol for the devices that accept push notifications."""

    async def save_subscription(self, subscription: PushSubscription) -> None:
        """Add a device, or move it to this person if someone else had it."""
        ...

    async def delete_subscription(self, user_id: UUID, endpoint: str) -> None:
        """Remove one of this person's devices."""
        ...

    async def delete_endpoint(self, endpoint: str) -> None:
        """Remove a device the push service says is gone, whoever it belongs to."""
        ...

    async def delete_all_subscriptions(self) -> None: ...
    async def list_subscriptions(self, user_id: UUID) -> list[PushSubscription]: ...
    async def list_all_subscriptions(self) -> list[PushSubscription]: ...
    async def claim(self, user_id: UUID, kind: str, keys: Sequence[str]) -> list[str]:
        """Mark these as told to this person; returns the ones that weren't already."""
        ...

    async def release(self, user_id: UUID, kind: str, keys: Sequence[str]) -> None:
        """Forget a claim: the message never reached anyone, or the problem went away."""
        ...

    async def list_claimed(self, user_id: UUID, kind: str) -> list[str]: ...
    async def prune_sent(self, before: datetime) -> None: ...


class DataProvider(Protocol):
    """Central unified data provider interface.

    Implemented by DatabaseDataProvider; tests can supply their own implementation.
    """

    @property
    def accounts(self) -> AccountRepository: ...

    @property
    def transactions(self) -> TransactionRepository: ...

    @property
    def categories(self) -> CategoryRepository: ...

    @property
    def rules(self) -> RuleRepository: ...

    @property
    def bills(self) -> BillRepository: ...

    @property
    def budgets(self) -> BudgetRepository: ...

    @property
    def goals(self) -> GoalRepository: ...

    @property
    def dashboard(self) -> DashboardRepository: ...

    @property
    def bank_connections(self) -> BankConnectionRepository: ...

    @property
    def settings(self) -> SettingsRepository: ...

    @property
    def users(self) -> UserRepository: ...

    @property
    def ai(self) -> AIRepository: ...

    @property
    def merchant_icons(self) -> MerchantIconRepository: ...

    @property
    def notifications(self) -> NotificationRepository: ...
