"""Abstract repository protocols and data provider interfaces.

Decouples UI routing and business logic from the persistence layer
(SQLite / PostgreSQL via SQLAlchemy) and makes services easy to test with fakes.
"""

from collections.abc import Sequence
from datetime import date, datetime
from decimal import Decimal
from typing import Any, Protocol
from uuid import UUID

from kash.domain.models import (
    Account,
    AIRun,
    AISuggestion,
    BalanceSnapshot,
    BankConnection,
    Bill,
    BillDetectionCandidate,
    BillOccurrence,
    BillStatus,
    Budget,
    CandidateStatus,
    Category,
    CategoryBudgetProgress,
    CategoryGroup,
    DashboardSummary,
    ExternalAccount,
    ExternalAccountSet,
    ExternalTransaction,
    Goal,
    MerchantIcon,
    PushSubscription,
    Rule,
    Transaction,
    User,
    UserSettings,
)


class AccountRepository(Protocol):
    """Protocol for account management operations."""

    async def list_accounts(
        self, user_id: UUID, include_inactive: bool = False
    ) -> list[Account]: ...
    async def get_account(self, account_id: UUID) -> Account | None: ...
    async def get_by_external_id(self, connection_id: UUID, external_id: str) -> Account | None: ...
    async def create_account(self, account: Account) -> Account: ...
    async def update_account(self, account: Account) -> Account: ...
    async def relink_account(
        self, account_id: UUID, connection_id: UUID, external_id: str
    ) -> Account: ...
    async def delete_account(self, account_id: UUID) -> bool: ...
    async def list_balance_snapshots(self, user_id: UUID) -> list[BalanceSnapshot]: ...
    async def save_balance_snapshot(self, snapshot: BalanceSnapshot) -> None: ...


class TransactionRepository(Protocol):
    """Protocol for transaction ledger operations."""

    async def list_transactions(
        self,
        user_id: UUID,
        account_id: UUID | None = None,
        category_id: UUID | None = None,
        start_date: date | None = None,
        end_date: date | None = None,
        search: str | None = None,
        limit: int = 50,
        offset: int = 0,
    ) -> list[Transaction]: ...
    async def get_transaction(self, tx_id: UUID) -> Transaction | None: ...
    async def get_by_external_id(
        self, account_id: UUID, external_id: str
    ) -> Transaction | None: ...
    async def find_by_fingerprint(
        self, account_id: UUID, fingerprint: str
    ) -> Transaction | None: ...
    async def list_by_fingerprint(
        self, account_id: UUID, fingerprint: str
    ) -> list[Transaction]: ...
    async def pending_totals(self, user_id: UUID) -> dict[UUID, Decimal]: ...
    async def create_transaction(self, tx: Transaction) -> Transaction: ...
    async def update_transaction(self, tx: Transaction) -> Transaction: ...
    async def delete_transaction(self, tx_id: UUID) -> bool: ...
    async def delete_by_account(self, account_id: UUID) -> int: ...


