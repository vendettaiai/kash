class BankProvider(Protocol):
    """Protocol for external bank synchronization providers (e.g. SimpleFIN)."""

    @property
    def provider_name(self) -> str: ...

    async def exchange_token(self, setup_token: str) -> tuple[str, str]:
        """Exchange setup token for (institution_name, access_credentials)."""
        ...

    async def fetch_account_set(
        self,
        credentials: str,
        since: datetime | None = None,
        account_ids: list[str] | None = None,
    ) -> ExternalAccountSet:
        """Accounts, balances and transactions posted since ``since`` (plus pending ones),
        all from one provider request. ``account_ids`` limits it to those accounts."""
        ...

    async def fetch_accounts(self, credentials: str) -> list[ExternalAccount]:
        """Fetch normalized accounts from provider."""
        ...

    async def fetch_transactions(
        self,
        credentials: str,
        since: datetime | None = None,
        until: datetime | None = None,
    ) -> list[ExternalTransaction]:
        """Fetch normalized transactions from provider within query window."""
        ...

    async def test_connection(self, credentials: str) -> bool:
        """Validate credentials without modifying state."""
        ...


